#!/usr/bin/env bash
# Writes docs/api/ from the ## doc comments in addons/strongbox/, using Godot's own doctool.
#   tools/gen_api_docs.sh          regenerate docs/api/
#   tools/gen_api_docs.sh --check  fail if docs/api/ is out of date (used by CI)
# Needs the pinned Godot (tools/pins.env) on PATH as `godot`.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

check=0
if [[ "${1:-}" == "--check" ]]; then
	check=1
elif [[ -n "${1:-}" ]]; then
	echo "usage: tools/gen_api_docs.sh [--check]" >&2
	exit 2
fi
if ! command -v godot >/dev/null 2>&1; then
	echo "godot is not on PATH. Install the version in tools/pins.env." >&2
	exit 1
fi

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
mkdir -p "$work/xml" "$work/md"

godot --headless --path . --import >/dev/null 2>&1
if ! godot --headless --path . --doctool "$work/xml" --gdscript-docs res://addons/strongbox >"$work/doctool.log" 2>&1 \
		|| grep -E -q 'SCRIPT ERROR|Parse Error' "$work/doctool.log"; then
	cat "$work/doctool.log"
	echo "Godot's doctool failed." >&2
	exit 1
fi

# The converter: doctool XML in, one Markdown page per public class plus an index out.
cat > "$work/convert.gd" <<'GDSCRIPT'
extends SceneTree

const HEADER: String = "Generated by `tools/gen_api_docs.sh` from the `##` doc comments. Do not edit by hand."

var _classes: Array[String] = []


func _init() -> void:
	var args: PackedStringArray = OS.get_cmdline_user_args()
	var in_dir: String = args[0]
	var out_dir: String = args[1]
	var pages: Array[Dictionary] = []
	for file: String in DirAccess.get_files_at(in_dir):
		# Skip inner classes ("Outer._Inner.xml") and scripts without a class_name ("addons--...").
		if file.get_basename().contains(".") or file.contains("--"):
			continue
		pages.append(_parse(in_dir.path_join(file)))
	pages.sort_custom(func(a: Dictionary, b: Dictionary) -> bool: return a["name"] < b["name"])
	for page: Dictionary in pages:
		_classes.append(page["name"])
	var index: PackedStringArray = ["# Strongbox API", "", HEADER, ""]
	for page: Dictionary in pages:
		index.append("- [%s](%s.md): %s" % [page["name"], page["name"], _md(page["brief"])])
		_write(out_dir.path_join(page["name"] + ".md"), _page(page))
	_write(out_dir.path_join("index.md"), "\n".join(index) + "\n")
	quit(0)


func _parse(path: String) -> Dictionary:
	var page: Dictionary = {"name": "", "inherits": "", "experimental": false, "brief": "", "description": "",
		"signal": [], "constant": [], "member": [], "method": []}
	var xml: XMLParser = XMLParser.new()
	xml.open(path)
	var item: Dictionary = {}
	var text_target: String = ""
	while xml.read() == OK:
		var node: String = xml.get_node_name()
		match xml.get_node_type():
			XMLParser.NODE_ELEMENT:
				match node:
					"class":
						page["name"] = xml.get_named_attribute_value_safe("name")
						page["inherits"] = xml.get_named_attribute_value_safe("inherits")
						page["experimental"] = xml.has_attribute("experimental")
					"method", "signal", "constant", "member":
						item = {"kind": node, "name": xml.get_named_attribute_value_safe("name"), "params": [],
							"type": xml.get_named_attribute_value_safe("type"), "value": xml.get_named_attribute_value_safe("value"),
							"default": xml.get_named_attribute_value_safe("default"), "return": "void", "text": "",
							"qualifiers": xml.get_named_attribute_value_safe("qualifiers")}
						if node == "member" or node == "constant":
							text_target = "text"
					"return":
						item["return"] = xml.get_named_attribute_value_safe("type")
					"param":
						var param: String = "%s: %s" % [xml.get_named_attribute_value_safe("name"), xml.get_named_attribute_value_safe("type")]
						if xml.has_attribute("default"):
							param += " = " + xml.get_named_attribute_value("default")
						item["params"].append(param)
					"brief_description":
						text_target = "brief"
					"description":
						text_target = "text" if not item.is_empty() else "description"
			XMLParser.NODE_TEXT:
				var text: String = _clean(xml.get_node_data())
				if text == "" or text_target == "":
					continue
				if text_target == "text":
					item["text"] = text
				else:
					page[text_target] = text
			XMLParser.NODE_ELEMENT_END:
				if node in ["method", "signal", "constant", "member"]:
					if not str(item["name"]).begins_with("_"):
						page[node].append(item)
					item = {}
				if node in ["brief_description", "description", "member", "constant"]:
					text_target = ""
	return page


func _page(page: Dictionary) -> String:
	var out: PackedStringArray = ["# %s" % page["name"], "", HEADER, ""]
	if page["experimental"]:
		out.append_array(["**Experimental:** this API may change before 1.0.", ""])
	out.append_array(["Inherits: `%s`" % page["inherits"], "", _md(page["brief"]), ""])
	if page["description"] != "":
		out.append_array([_md(page["description"]), ""])
	var sections: Array = [["signal", "Signals"], ["constant", "Constants"], ["member", "Properties"], ["method", "Methods"]]
	for section: Array in sections:
		var items: Array = page[section[0]]
		if items.is_empty():
			continue
		out.append_array(["## %s" % section[1], ""])
		for item: Dictionary in items:
			out.append_array(["### `%s`" % item["name"], "", "```gdscript", _signature(item), "```", ""])
			if item["text"] != "":
				out.append_array([_md(item["text"]), ""])
	return "\n".join(out).strip_edges() + "\n"


func _signature(item: Dictionary) -> String:
	match item["kind"]:
		"method":
			var prefix: String = "static " if str(item["qualifiers"]).contains("static") else ""
			return "%sfunc %s(%s) -> %s" % [prefix, item["name"], ", ".join(item["params"]), item["return"]]
		"signal":
			return "signal %s(%s)" % [item["name"], ", ".join(item["params"])]
		"constant":
			return "const %s = %s" % [item["name"], item["value"]]
	var line: String = "var %s: %s" % [item["name"], item["type"]]
	return line + (" = " + str(item["default"]) if str(item["default"]) != "" else "")


## Joins the indented lines of a doc text.
func _clean(text: String) -> String:
	var lines: PackedStringArray = []
	for line: String in text.split("\n"):
		lines.append(line.strip_edges())
	return "\n".join(lines).strip_edges()


## Turns Godot's doc BBCode into Markdown.
func _md(text: String) -> String:
	var out: String = text
	var fences: RegEx = RegEx.create_from_string("\\[codeblock\\]\\n?([\\s\\S]*?)\\n?\\[/codeblock\\]")
	out = fences.sub(out, "\n```gdscript\n$1\n```\n", true)
	out = out.replace("[br]", "\n").replace("[b]", "**").replace("[/b]", "**").replace("[i]", "*").replace("[/i]", "*")
	out = RegEx.create_from_string("\\[code\\]([\\s\\S]*?)\\[/code\\]").sub(out, "`$1`", true)
	out = RegEx.create_from_string("\\[method ([\\w.]+)\\]").sub(out, "`$1()`", true)
	out = RegEx.create_from_string("\\[(?:param|member|constant|signal|enum) ([\\w.]+)\\]").sub(out, "`$1`", true)
	for known: String in _classes:
		out = out.replace("[%s]" % known, "[%s](%s.md)" % [known, known])
	out = RegEx.create_from_string("\\[([A-Z]\\w*)\\](?!\\()").sub(out, "`$1`", true)
	while out.contains("\n\n\n"):
		out = out.replace("\n\n\n", "\n\n")
	return out.strip_edges()


func _write(path: String, text: String) -> void:
	var file: FileAccess = FileAccess.open(path, FileAccess.WRITE)
	file.store_string(text)
	file.close()
GDSCRIPT

godot --headless --path . -s "$work/convert.gd" -- "$work/xml" "$work/md" >"$work/convert.log" 2>&1 || {
	cat "$work/convert.log"
	echo "Converting the doctool XML failed." >&2
	exit 1
}

if [[ "$check" -eq 1 ]]; then
	if ! diff -r -u docs/api "$work/md"; then
		echo "docs/api/ is out of date. Run tools/gen_api_docs.sh and commit the result." >&2
		exit 1
	fi
	echo "docs/api/ is up to date."
	exit 0
fi
rm -rf docs/api
mkdir -p docs/api
cp "$work/md"/*.md docs/api/
echo "Wrote $(find docs/api -name '*.md' | wc -l | tr -d ' ') pages to docs/api/."
